/** 授業の構成。道徳は、覚えることを確かめるのではなく、読み物から考える形にする */
function structureGuide(course: Course): string {
  if (course.higher) {
    return `  1. 「# 授業のタイトル」
  2. 「## この授業のねらい」（箇条書き 2〜3 個。「〜を説明できる」「〜を求められる」のように、できるようになることを書く）
  3. 本文（「## 」の見出しを 3〜5 個。大切な用語や定理は太字にする。前の授業のどの内容を使うかを、はじめに 1〜2 文で示す）
  4. 「## 例題」（解き方や考え方の筋道を省かない。分野に合わせて「## 設例」「## 研究から考える」などに変えてかまいません）
  5. 「## 確かめ問題」（3〜4 問。答えと、考え方の要点を「### 答え」にまとめる。用語を答えるだけの問いにせず、計算・説明・証明・あてはめの問いをふくめる）
  6. 「## ノートに書いてみましょう」（自分の言葉でまとめるための問いかけを 2〜3 個。ほかの科目や、身近な場面とのつながりを考える問いを 1 つふくめる）`
  }
  if (course.subject === 'moral') {
    return `  1. 「# 授業のタイトル」
  2. 「## この授業のねらい」（箇条書き 2 個。「〜について考える」の形にし、身につける態度を決めつけない）
  3. 「## お話」（自分で書いた読み物。登場人物が迷う場面で終え、結末で答えを示さない。分量の半分ほどを使う）
  4. 「## 考えてみましょう」（問いを 3〜4 個。登場人物の気持ち、自分ならどうするか、ちがう立場から見るとどうか）
  5. 「### 考えるヒント」（問いごとに、考える手がかりや、いくつかの見方を書く。正解は示さない）
  6. 「## ノートに書いてみましょう」（自分の経験や、これからの生活と結びつけて考える問いかけを 2 個）`
  }
  return `  1. 「# 授業のタイトル」
  2. 「## この授業のねらい」（箇条書き 2〜3 個）
  3. 本文（「## 」の見出しを 2〜4 個。大切な用語や決まりは太字にする）
  4. 「## 例題」（教科に合わせて「## 例文」「## 資料から考える」「## やってみましょう」などに変えてかまいません）
  5. 「## 確かめ問題」（3〜4 問。答えは「### 答え」にまとめる）
  6. 「## ノートに書いてみましょう」（自分の言葉でまとめるための問いかけを 2〜3 個。ほかの教科や身近な場面とのつながりを考える問いを 1 つふくめる）`
}

