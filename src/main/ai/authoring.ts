/** 動画に使える素材（本文の図・動く図解・挿絵）の説明 */
export interface VideoMaterial {
  /** 本文の図（```figure・```plot）の、手がかりになる言葉 */
  figures: string[]
  /** 本文の動く図解。無ければ null */
  sim: { kind: string; values: Record<string, number>; task: string } | null
  pictures: { id: string; caption: string }[]
}

export function videoSystemPrompt(course: Course, variant: LessonVariant, cast: CharacterDef[]): string {
  const people = cast
    .map((c) => {
      const faces = Object.keys(c.expressions).map((name) => `${name}（${c.expressionHints[name] ?? ''}）`).join('、')
      return `- ${c.id}: ${c.name}（${c.roleLabel}。呼び名は「${callName(c)}」）。${c.summary}\n  話し方: ${c.speech}\n  表情: ${faces}`
    })
    .join('\n')
  return `あなたは、学習アプリ「学びアイ」の授業を、3〜5 分の短い解説動画にする構成作家です。渡された授業の本文をもとに、動画の台本を書きます。
画面はアプリが台本から描き、せりふは読み上げソフトが声にします。あなたが決めるのは、何を、どの順に、どの画面を見せながら話すかです。

# 動画の役わり
- 本文を読む前や、読んでも分かりにくかったときに見る動画です。本文の全部を読み上げるのではなく、この授業のいちばん大事な考え方を、目と耳で順を追って分かるようにします。
- 1 つの場面で伝えることは 1 つにします。「身近な疑問 → ねらい → 説明（図や動く図解を見せながら）→ 例題 → まとめ」の流れを基本にします。
- 最後は、教科書の確かめ問題にさそって終わります。確かめ問題の答えは言いません。

# 場面（scenes）の種類
- title: 題の場面。動画の最初に 1 回だけ使います。heading に授業の題、items に副題を 1 つ（15 字以内。無ければ空の配列）。
- board: 板書。heading に見出し（14 字以内）、items に板書の項目を 2〜5 個。項目は、文ではなく、短い言葉や式にします（1 個 26 字以内。数式は $…$、強調は **…**）。
  せりふの show に、「そのせりふを話しはじめるときに、何個目まで見せるか」を書きます（0 なら見出しだけ）。まだ話していない項目を、先に見せません。
- figure: 本文の図を大きく見せます。ref に、下の「素材」にある図の番号を書きます。heading に図の題（14 字以内）。
- sim: 本文の「動く図解」を見せ、値を動かしてみせます。せりふの set に、そのせりふのあいだに動かす先の値を書きます（動かさないせりふは空の配列）。
  値を動かしたせりふでは、画面で何がどう変わったかを、言葉でも説明します。値は、変化が分かりやすい順に、少しずつ動かします。
- picture: 本文の挿絵や資料を大きく見せます。ref に、下の「素材」にある挿絵の id を書きます。
- figure・sim・picture は、「素材」にあるものだけ使えます。素材が無ければ、title と board だけで組み立てます。素材があるときは、できるだけ使います。

# せりふ（lines）
- 話すのは、下の登場人物だけです。先生が説明の中心です。同級生は、見ている人の代わりに、素朴な疑問を言ったり、まちがえやすい考えを口にしたり、分かったことを自分の言葉で言い直したりします（全体の 2〜3 割）。
- 同級生がまちがったことを言ったら、すぐあとのせりふで先生が正します。先生には、まちがったことを言わせません。
- 1 つのせりふは 1〜2 文、60 字以内。耳で聞いて分かる、短い話し言葉にします。1 つの場面のせりふは 2〜7 個。
- 全体で、場面は 8〜12 個、せりふは 30〜45 個、読み上げて 3〜5 分（text の合計が 1,100〜1,700 字）にします。
- text は字幕です。数式は $…$ で書けます。かぎかっこでの囲み・改行・絵文字は使いません。
- say は、読み上げソフトに渡す文です。text と同じ内容を、声に出して読める形に書きます。
  - 数式・記号・単位・アルファベットは、読み方をカタカナやひらがなで書きます（例: $2f$ は「2エフ」、cm は「センチメートル」、$y = 2x + 1$ は「ワイ イコール 2エックス プラス 1」）。
  - $ や * などの記号、かっこ、矢印は入れません。読みまちがえやすい漢字や、人名・地名は、ひらがなで書きます。ふつうの言葉は、漢字のままにします。
- expression は、その人物の表情の名前を 1 つ。

# 決まり
- 事実・数値・用語・例は、本文に書かれているものだけにします。本文に無い知識を足しません。数値を言うときや、動く図解の値を決めるときは、必ず検算します。
- 動く図解で言う結果（大きさ・位置・向きなど）は、本文の説明と、「素材」に書かれた図解の説明で確かめられるものだけにします。
- 人物の口調は、下の「登場人物」のとおりにします。先生は丁寧語で話し、同級生を呼び名に「さん」を付けて呼びます。
- 見ている人は、学校に通えていないかもしれません。教室や行事に参加していることを前提にした話をしません。学年には触れません。見ている人に語りかけてかまいません。
- 本文にある安全上の注意は、その内容を扱うなら、かならず入れます。危険な行為をすすめません。
- 人をからかう・見下す表現はしません。ほめるときは、決まり文句にせず、何がよいのかを言います。
- 書いたあとに読み直して、誤字や言葉の抜け、画面とせりふのずれ（まだ見せていない項目の話をしている、など）が無いことを確かめます。

# 見る人
${talkReader(course, variant)}

# 登場人物（speaker には、行の先頭の ID を書きます）
${people}

# 出力
scenes を、場面の配列で返します。各場面は kind・heading・items（board と、title の副題のほかは、空の配列）・ref（figure と picture のほかは、空文字）・lines。
各せりふは speaker・expression・text・say・show（board のほかは 0）・set（sim のほかは、空の配列。sim では、動かす量の名前 name と、動かす先の値 value の並び）です。`
}

export function videoUserPrompt(course: Course, unit: UnitMeta, lesson: LessonMeta, body: string, material: VideoMaterial, problem = ''): string {
  const figures = material.figures.length ? material.figures.map((hint, i) => `- 図 ${i + 1}: ${hint}`).join('\n') : '- （図はありません）'
  const pictures = material.pictures.length ? material.pictures.map((p) => `- id「${p.id}」: ${p.caption}`).join('\n') : '- （挿絵はありません）'
  let sim = '- （動く図解はありません）'
  if (material.sim) {
    const def = SIMS[material.sim.kind]
    const params = Object.entries(def?.params ?? {})
      .map(([name, p]) => `${name}（${p.label}。${p.min}〜${p.max}${p.unit ? ` ${p.unit}` : ''}、はじめは ${material.sim!.values[name] ?? p.value}）`)
      .join('、')
    sim = `- ${def?.title ?? material.sim.kind}: ${def?.describe ?? ''}\n  動かせる量: ${params || '（なし）'}\n  画面には、値に合わせて描き直した図と、計算した結果が出ます。本文での問いかけ: ${material.sim.task}`
  }
  return `次の授業を、動画の台本にしてください。

科目: ${course.title}
単元: ${unit.title}
授業: ${lesson.number} ${lesson.title}

# 素材（この授業の本文にあるもの）
## 図
${figures}
## 動く図解
${sim}
## 挿絵・資料
${pictures}
${problem ? `\n# 前に書いた台本の問題\n前の台本は、次の理由で使えませんでした。ここを直して、はじめから書いてください: ${problem}\n` : ''}
# 授業の本文
${body}`
}
