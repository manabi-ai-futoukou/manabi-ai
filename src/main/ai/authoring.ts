    const lower = /^(1|2|1・2) 年$/.test(course.label)
    return `${course.label}の小学生です。${lower ? 'せりふは、ひらがなを中心にし、漢字はその学年までに習うものだけを使います。1 文を短くします。' : 'その学年までに習う漢字を中心にし、むずかしい言葉は使わないか、すぐに言いかえます。'}`
